/* =============================================================
   ทำไฟล์ "ข้อสอบที่ต้องเติม" ส่งให้เจ้าของข้อสอบ จากไฟล์ชุดข้อสอบต้นฉบับ
   - ชีต "ต้องเติม": ทุกข้อที่ยังใช้ไม่ได้ + ช่องว่างให้เจ้าของกรอกกลับ (เฉลย / ตัวเลือกที่เพิ่ม)
   - ชีต "ขอให้ยืนยัน": ข้อที่ระบบอ่านได้แต่มีความไม่แน่นอน
   รัน: node scripts/export-exam-gaps.mjs [ไฟล์ข้อสอบ.xlsx] [ไฟล์ผลลัพธ์.xlsx]
   ============================================================= */
import { readFileSync, writeFileSync } from "node:fs";
import XLSX from "xlsx";
import { parseWorkbook } from "./lib/exam-parse.mjs";

const SRC = process.argv[2] ?? "commission-app/ข้อสอบ Com/ชุดข้อสอบ SE New Comer_Up Level.xlsx";
const OUT = process.argv[3] ?? "commission-app/ข้อสอบ Com/ข้อสอบที่ต้องเติม.xlsx";
const { topics } = parseWorkbook(readFileSync(SRC));

const need = (problems, nOpts) => {
  const p = problems.join(" ; ");
  if (/ไม่มีเฉลย/.test(p)) return "ระบุตัวเลือกที่ถูก (หรือไฮไลต์สีเขียวที่ตัวเลือกที่ถูกในไฟล์ต้นฉบับ)";
  if (/ตัวเลือกไม่ครบ/.test(p)) return `ตัวเลือกที่มีอยู่ ${nOpts} ข้อถูกใช้เป็นเฉลย ต้องเพิ่มตัวเลือกหลอกอีก 3 ข้อ (ความยาว/รูปแบบใกล้เคียงเฉลย)`;
  return "ตรวจและแก้ตามปัญหาที่ระบุ";
};

const rows = [["ลำดับ", "หัวข้อ", "ชีตในไฟล์", "ข้อที่", "แถวในไฟล์", "โจทย์", "ตัวเลือกที่ระบบอ่านได้ (✓ = ที่ระบบถือว่าถูก)", "ปัญหา", "สิ่งที่ต้องส่งให้", "← เจ้าของกรอก: ตัวเลือกที่ถูก", "← เจ้าของกรอก: ตัวเลือกหลอกที่เพิ่ม"]];
let n = 0;
for (const t of topics) {
  for (const q of t.questions) {
    if (!q.problems.length) continue;
    n++;
    rows.push([
      n,
      t.title,
      t.sheet,
      q.sort,
      q.srcRow,
      q.body,
      q.options.map((o, i) => `${i + 1}) ${o.body}${o.correct ? " ✓" : ""}`).join("\n"),
      q.problems.join(" ; "),
      need(q.problems, q.options.length),
      "",
      "",
    ]);
  }
}

